const add=function(a, b){
return a+b;
}

const sub=function(a, b){
return a-b;
}


const mul=function(a, b){
return a*b;
}

const aofcircle=function(r){
    return 3.14*r*r;
}

const evenodd=function(a){
    return (a%2==0)?`${a} is even`:`${a}is odd`
}

const cube=function(a){
    return a*a*a;
}

export {add , sub , mul , aofcircle , evenodd , cube};
